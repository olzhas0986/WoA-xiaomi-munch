#!/usr/bin/env python3
"""Generate a read-only BCD sector overlay for the exact existing WinPE media.

Replace the unused, disabled EMS element with DisableCrashAutoReboot=true.
Same-size key/value; its lf hint ('2600') and sorted position remain valid.
No hive allocation, filesystem update, or phone storage write is performed.
"""
from pathlib import Path
import hashlib,struct,subprocess,re,zlib,json
R=Path(__file__).resolve().parents[1]
p=(R/'out/winpe/media/efi/microsoft/boot/bcd').read_bytes()
assert hashlib.sha256(p).hexdigest()=='b90ef16b94c3dda7d76cc39840befaa9786887517445c3b6f47ebc806d0ab105'
q=bytearray(p)
key=0x1000+0x1d98+4
assert p[key:key+2]==b'nk' and struct.unpack_from('<H',p,key+72)[0]==8
assert p[key+76:key+84]==b'260000b0'
parent=struct.unpack_from('<I',p,key+16)[0]
assert parent==0xd90
li=0x1004+struct.unpack_from('<I',p,0x1004+parent+28)[0]
assert p[li:li+4]==b'lf\x0b\x00'
entries=[struct.unpack_from('<II',p,li+4+i*8) for i in range(11)]
assert entries[-1][0]==0x1d98 and p[li+4+10*8+4:li+4+11*8]==b'2600'
names=[p[0x1004+k+76:0x1004+k+84] for k,h in entries]
assert names==sorted(names) and names[-2]==b'26000022'
vlist=struct.unpack_from('<I',p,key+40)[0]
v=0x1004+struct.unpack_from('<I',p,0x1004+vlist)[0]
assert p[v:v+2]==b'vk' and struct.unpack_from('<III',p,v+4)==(0x80000001,0,3)
assert p[v+20:v+27]==b'Element'
q[key+76:key+84]=b'26000024';q[v+8]=1
changes=[i for i in range(len(p)) if p[i]!=q[i]]
assert len(changes)==3 and len({i//4096 for i in changes})==1
sector=changes[0]//4096
rows=[]
for volume in ('esp','win'):
 image=R/f'out/winpe/{volume}-winpe-4kn.img'
 fat=subprocess.check_output(['mshowfat','-i',str(image),'::/efi/microsoft/boot/bcd'],text=True)
 match=re.search(r'<(\d+)-(\d+)>',fat);assert match
 first,last=map(int,match.groups());assert last-first==3
 with image.open('rb') as f:
  b=f.read(4096);bps=struct.unpack_from('<H',b,11)[0];spc=b[13]
  reserved=struct.unpack_from('<H',b,14)[0];fat_size=struct.unpack_from('<I',b,36)[0]
  assert bps==4096 and spc==1
  lba=reserved+b[16]*fat_size+(first-2)*spc
  f.seek(lba*4096);assert f.read(len(p))==p
 rows.append(lba+sector)
start=sector*4096;block=p[start:start+4096]
text='// Generated by tools/prepare-bcd-noreboot.py; exact-media RAM overlay.\n'
text+='STATIC CONST EFI_LBA BcdSector[2] = {'+', '.join(map(str,rows))+'};\n'
text+=f'#define BCD_ORIGINAL_CRC 0x{zlib.crc32(block):08x}U\n'
text+='STATIC CONST struct { UINT16 Offset; UINT8 Before, After; } BcdChanges[] = {\n'
text+=''.join(f'  {{ {i-start}, 0x{p[i]:02x}, 0x{q[i]:02x} }},\n' for i in changes)+'};\n'
(R/'firmware/munch/BootManager/BcdOverlay.h').write_text(text)
(R/'out/winpe/bcd-noreboot-preview').write_bytes(q)
print(json.dumps({'sector_lbas':rows,'byte_changes':changes,'disk_writes':False}))
